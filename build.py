"""Build extension.py = header + Newtone codec (src/ntcodec.py) + live tools (src/tools.py).
BetterFL loads extension.py as one module, so the codec is inlined instead of imported."""
import ast
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = '''"""MCP Bridge Newtone: control Image-Line Newtone from BetterFL MCP Bridge.

Free extension. GENERATED by build.py from src/ntcodec.py and src/tools.py: edit those.
Needs BetterFL Bridge's native newtone_* functions (better-fl-mcp bridge/src/newtone.cpp); with an
older bridge every tool answers with a "restart FL" error.
"""
'''


def main():
    codec = open(os.path.join(HERE, "src", "ntcodec.py"), encoding="utf-8").read()
    codec = codec.split('\nif __name__ == "__main__":')[0]
    codec = re.sub(r'^""".*?"""\n', "# --- Newtone state / project XML codec (format notes: src/ntcodec.py) ---\n",
                   codec, count=1, flags=re.S)
    tools = open(os.path.join(HERE, "src", "tools.py"), encoding="utf-8").read()
    out = HEADER + codec.strip("\n") + "\n\n\n" + tools.strip("\n") + "\n"
    out = re.sub(r"\n{4,}", "\n\n\n", out)
    ast.parse(out)
    open(os.path.join(HERE, "extension.py"), "w", encoding="utf-8").write(out)
    print("extension.py:", len(out.splitlines()), "lines")


if __name__ == "__main__":
    main()
